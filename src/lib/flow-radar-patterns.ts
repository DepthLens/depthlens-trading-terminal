/* ---------------- detection ---------------- */
export function detectPatterns(candles: AtlasCandle[], tf: AtlasTimeframe, enabled?: PatternId[]): PatternEvent[] {
  const n = candles.length;
  if (n < WARMUP + 1 || !isAtlasTimeframe(tf)) return [];
  const K = ATLAS_DATA.calib[tf];
  const o = new Float64Array(n), h = new Float64Array(n), l = new Float64Array(n), c = new Float64Array(n);
  const v = new Float64Array(n), d = new Float64Array(n);
  for (let i = 0; i < n; i++) { const k = candles[i]!; o[i] = k.open; h[i] = k.high; l[i] = k.low; c[i] = k.close; v[i] = k.volume; d[i] = k.delta; }

  // ATR14 (Wilder), avg volume of previous 20, delta ratio, candle shape
  const atr = new Float64Array(n), vr = new Float64Array(n), dr = new Float64Array(n), rng = new Float64Array(n);
  const pos = new Float64Array(n), upw = new Float64Array(n), lww = new Float64Array(n);
  const hh20 = new Float64Array(n), ll20 = new Float64Array(n), cvd10 = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    const pc = i > 0 ? c[i - 1]! : c[0]!;
    const tr = Math.max(h[i]! - l[i]!, Math.abs(h[i]! - pc), Math.abs(l[i]! - pc));
    atr[i] = i === 0 ? tr : atr[i - 1]! + (tr - atr[i - 1]!) / 14;
    // direct sums (no running total, so no rounding drift on long histories)
    if (i >= 20) { let vs = 0; for (let j = i - 20; j < i; j++) vs += v[j]!; vr[i] = v[i]! / (vs / 20); } else vr[i] = NaN;
    if (i >= 9) { let ds = 0; for (let j = i - 9; j <= i; j++) ds += d[j]!; cvd10[i] = ds; } else cvd10[i] = NaN;
    dr[i] = v[i]! > 0 ? d[i]! / v[i]! : 0;
    rng[i] = h[i]! - l[i]!;
    const r = rng[i]! > 0 ? rng[i]! : 1;
    pos[i] = rng[i]! > 0 ? (c[i]! - l[i]!) / r : 0.5;
    upw[i] = (h[i]! - Math.max(o[i]!, c[i]!)) / r;
    lww[i] = (Math.min(o[i]!, c[i]!) - l[i]!) / r;
    if (i >= 20) { let mx = -Infinity, mn = Infinity; for (let j = i - 20; j < i; j++) { if (h[j]! > mx) mx = h[j]!; if (l[j]! < mn) mn = l[j]!; } hh20[i] = mx; ll20[i] = mn; }
    else { hh20[i] = NaN; ll20[i] = NaN; }
  }
  // previous UTC day high / low
  const pdh = new Float64Array(n).fill(NaN), pdl = new Float64Array(n).fill(NaN);
  { let day = -1, dH = -Infinity, dL = Infinity, pH = NaN, pL = NaN;
    for (let i = 0; i < n; i++) {
      const dd = Math.floor(candles[i]!.time / 86400000);
      if (dd !== day) { if (day !== -1) { pH = dd === day + 1 ? dH : NaN; pL = dd === day + 1 ? dL : NaN; } day = dd; dH = -Infinity; dL = Infinity; }
      if (h[i]! > dH) dH = h[i]!; if (l[i]! < dL) dL = l[i]!;
      pdh[i] = pH; pdl[i] = pL;
    } }

  const raw: Record<PatternId, Int8Array> = {} as any;
  const ids = Object.keys(PATTERN_INFO) as PatternId[];
  for (const id of ids) raw[id] = new Int8Array(n);
  const sgn = (x: number) => (x > 0 ? 1 : x < 0 ? -1 : 0);
  const sArr = new Int8Array(n);
  for (let i = 0; i < n; i++) sArr[i] = sgn(Math.abs(dr[i]!) >= 0.15 ? dr[i]! : 0) * sgn(c[i]! - o[i]!);

  for (let i = 0; i < n; i++) {
    const up = c[i]! > o[i]!, dn = c[i]! < o[i]!;
    const adr = Math.abs(dr[i]!);
    // A
    const a = vr[i]! >= 1.5 && adr >= K.dr90;
    raw.A_flow_momentum[i] = a && dr[i]! > 0 && up && pos[i]! > 0.6 ? 1 : a && dr[i]! < 0 && dn && pos[i]! < 0.4 ? -1 : 0;
    // B
    raw.B_prevday_sweep[i] = h[i]! > pdh[i]! && c[i]! < pdh[i]! && dr[i]! < 0 ? -1 : l[i]! < pdl[i]! && c[i]! > pdl[i]! && dr[i]! > 0 ? 1 : 0;
    // C, R
    const sh = h[i]! > hh20[i]! && c[i]! < hh20[i]! && vr[i]! >= 1.5;
    const sl = l[i]! < ll20[i]! && c[i]! > ll20[i]! && vr[i]! >= 1.5;
    raw.C_sweep_absorb[i] = sh && dr[i]! > 0 ? -1 : sl && dr[i]! < 0 ? 1 : 0;
    raw.R_reversal_watch[i] = sh && dr[i]! < 0 && pos[i]! < 0.35 ? -1 : sl && dr[i]! > 0 && pos[i]! > 0.65 ? 1 : 0;
    // D
    const ab = vr[i]! >= 2 && adr >= K.dr75;
    raw.D_absorption[i] = ab && dr[i]! > 0 && pos[i]! < 0.4 ? -1 : ab && dr[i]! < 0 && pos[i]! > 0.6 ? 1 : 0;
    // E
    raw.E_cvd_divergence[i] = c[i]! > hh20[i]! && cvd10[i]! < 0 ? -1 : c[i]! < ll20[i]! && cvd10[i]! > 0 ? 1 : 0;
    // F
    const cl = vr[i]! >= 4 && rng[i]! >= 2.5 * atr[i]!;
    raw.F_climax[i] = cl && up ? -1 : cl && dn ? 1 : 0;
    // G
    if (i >= 2) {
      const sd = sgn(dr[i]!);
      const st = sArr[i]! > 0 && sArr[i - 1]! > 0 && sArr[i - 2]! > 0 && sd === sgn(dr[i - 1]!) && sd === sgn(dr[i - 2]!);
      raw.G_delta_streak[i] = st ? sd : 0;
    }
    // H
    raw.H_wick_delta[i] = lww[i]! >= 0.6 && dr[i]! > 0.1 ? 1 : upw[i]! >= 0.6 && dr[i]! < -0.1 ? -1 : 0;
    // X2
    const big = rng[i]! >= 2 * atr[i]!;
    raw.X2_upthrust_spring[i] = h[i]! > hh20[i]! && big && c[i]! < hh20[i]! ? -1 : l[i]! < ll20[i]! && big && c[i]! > ll20[i]! ? 1 : 0;
    // X3
    raw.X3_div_volume[i] = h[i]! > hh20[i]! && cvd10[i]! < 0 && vr[i]! >= 2 && pos[i]! < 0.5 ? -1
                         : l[i]! < ll20[i]! && cvd10[i]! > 0 && vr[i]! >= 2 && pos[i]! > 0.5 ? 1 : 0;
  }

  const want = new Set(enabled ?? ids);
  const events: PatternEvent[] = [];
  const profiles = ATLAS_DATA.profiles[tf];
  for (const id of ids) {
    if (!want.has(id)) continue;
    const last: Record<number, number> = { 1: -1e9, [-1]: -1e9 };
    const prof = profiles[id] ?? null;
    for (let i = 0; i < n; i++) {
      const s = raw[id]![i]!;
      if (!s) continue;
      if (i - last[s]! > COOLDOWN) {
        last[s] = i;
        if (i >= WARMUP) events.push({ index: i, time: candles[i]!.time, pattern: id, side: s as 1 | -1,
          label: prof?.status ?? "Watch", name: PATTERN_INFO[id].name, profile: prof });
      }
    }
  }
  return events.sort((x, y) => x.index - y.index);
}

/* ---------------- hover text ---------------- */
const f = (x: number | undefined, d = 2) => (x === undefined || x === null ? "–" : x.toFixed(d));
const sR = (x: number | undefined) => (x === undefined || x === null ? "–" : (x >= 0 ? "+" : "") + x.toFixed(2) + "R");

export function describeEvent(e: PatternEvent, tf: AtlasTimeframe): string[] {
  const p = e.profile, info = PATTERN_INFO[e.pattern];
  const side = e.side === 1 ? "Buy side" : "Sell side";
  const lines = [`${e.label}: ${info.name} · ${side} · ${tf}`, info.rule];
  if (!p) return [...lines, "No measured data for this timeframe."];
  lines.push(`Seen ${f(p.perMonth, 1)}×/month on ${tf}` + (p.monthMin !== undefined ? ` (range ${p.monthMin}–${p.monthMax})` : ""));
  if (p.lowSample) lines.push("Small sample — treat numbers as rough.");
  if (p.moveMedPct !== undefined) {
    lines.push(`Move in 24 candles: median ${f(p.moveMedPct)}% (${f(p.moveP25Pct)}–${f(p.moveP75Pct)}%), peak ~candle ${p.peakBarMed}`);
    lines.push(`Went 1 ATR against first: ${f(p.againstFirstPct, 0)}%`);
    lines.push(`Hit before 1 ATR stop: 0.5 ATR ${f(p.hit05, 0)}% · 1 ATR ${f(p.hit1, 0)}% · 2 ATR ${f(p.hit2, 0)}%`);
    lines.push(`Avg per trade @1 ATR: ${sR(p.r1Gross)} before fees, ${sR(p.r1Net)} after (fees ≈ ${f(p.feeR)}R)`);
    lines.push(`2025 / 2026 after fees @2 ATR: ${sR(p.r2Net2025)} / ${sR(p.r2Net2026)}`);
    if (info.kind === "reversal" && p.stR2Net !== undefined)
      lines.push(`Stop beyond the swept high/low (median ${f(p.stStopPct)}%), 2R target: hit ${f(p.stHit2, 0)}%, after fees ${sR(p.stR2Net)} (2025 ${sR(p.stR2Net2025)} / 2026 ${sR(p.stR2Net2026)})`);
  }
  lines.push("Past BTCUSDT results 2025–2026, not a prediction.");
  return lines;
}

export function reversalNotes(tf: AtlasTimeframe): string[] {
  const r = ATLAS_DATA.reversal[tf];
  return [
    `${tf}: ~${r.turnsPerMonth} real turns (≥3 ATR) a month, median swing ${r.swingMedPct}% over ~${r.swingBarsMed} candles.`,
    `Only ${r.baseTurnChancePct}% of new 20-candle highs/lows become a real turn.`,
    "Seen more often at real turns: " + r.top.map((t) => `${t.reason} (×${t.lift})`).join(", ") + ".",
    `Most turns (UTC): ${r.busiestHoursUtc}.`,
  ];
}
