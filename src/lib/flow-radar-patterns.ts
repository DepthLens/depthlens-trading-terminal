/**
 * Flow Radar — Pattern Atlas (ADD-ON). Does NOT replace or change the existing Flow Radar.
 *
 * What it does
 *  - Detects 11 order-flow patterns on 1m, 5m, 15m, 30m, 1h, 4h candles (with delta).
 *  - Every pattern carries its OWN measured numbers for THAT timeframe, from BTCUSDT Futures
 *    1 Jan 2025 – 31 Oct 2026 (22 months): how many times a month, how far price went,
 *    hit % at 0.5 / 1 / 2 ATR, average R before and after fees, fee cost in R.
 *  - Label is "Setup" only where the result stayed positive after fees in BOTH 2025 and 2026.
 *    Everything else is "Watch". Never "Signal", never a promised accuracy.
 *
 * Rules use only the signal candle and the candles before it (no future data).
 * Pure functions, no network, no storage. Generated by gen_ts.py — numbers are not hand-typed.
 */

export type AtlasTimeframe = "1m" | "5m" | "15m" | "30m" | "1h" | "4h";

export interface AtlasCandle {
  time: number;   // open time, ms UTC
  open: number; high: number; low: number; close: number;
  volume: number; // base volume
  delta: number;  // taker buy volume − taker sell volume
}

export type PatternId =
  | "A_flow_momentum" | "B_prevday_sweep" | "C_sweep_absorb" | "R_reversal_watch" | "D_absorption"
  | "E_cvd_divergence" | "F_climax" | "G_delta_streak" | "H_wick_delta" | "X2_upthrust_spring" | "X3_div_volume";

export interface PatternProfile {
  perMonth: number; events: number; status: "Setup" | "Watch"; lowSample: boolean;
  monthMin?: number; monthMax?: number;
  moveMedPct?: number; moveP25Pct?: number; moveP75Pct?: number; moveMedAtr?: number; peakBarMed?: number;
  againstFirstPct?: number;
  hit05?: number; hit1?: number; hit2?: number;
  r1Gross?: number; r1Net?: number; r2Gross?: number; r2Net?: number; feeR?: number;
  r2Net2025?: number; r2Net2026?: number;
  stHit2?: number; stR2Net?: number; stStopPct?: number; stR2Net2025?: number; stR2Net2026?: number;
}

export interface PatternEvent {
  index: number; time: number; pattern: PatternId; side: 1 | -1; // 1 = buy side, -1 = sell side
  label: "Setup" | "Watch"; name: string; profile: PatternProfile | null;
}

